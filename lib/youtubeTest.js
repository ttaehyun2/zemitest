/** 점수(0~100)를 예상 구독자 수로 환산합니다. */
export function toSubs(score) {
  const n = Math.round(50 * Math.pow(10, score / 18.7));
  return Math.min(n, 15000000);
}

/** 구독자 수를 한국식으로 읽기 좋게 표기합니다. */
export function formatSubs(n) {
  if (n >= 100000000) return `${(n / 100000000).toFixed(1)}억`;
  if (n >= 10000) {
    const man = n / 10000;
    return man >= 100 ? `${Math.round(man)}만` : `${man.toFixed(1).replace(/\.0$/, "")}만`;
  }
  if (n >= 1000) return `${(n / 1000).toFixed(1).replace(/\.0$/, "")}천`;
  return `${n}`;
}

