export function classify(econPct, socPct) {
  // econPct: 100이면 완전 보수(시장), 0이면 완전 진보(분배)
  // socPct : 100이면 완전 자유(개인), 0이면 완전 사회(질서)
  const e = econPct - 50;
  const s = socPct - 50;
  if (Math.abs(e) < 12 && Math.abs(s) < 12) return QUADRANTS.center;
  if (e < 0 && s >= 0) return QUADRANTS.libLeft;
  if (e < 0 && s < 0) return QUADRANTS.authLeft;
  if (e >= 0 && s >= 0) return QUADRANTS.libRight;
  return QUADRANTS.authRight;
}
