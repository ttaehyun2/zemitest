export const MAX_BY_TYPE = (() => {
  const max = {};
  Object.keys(TYPES).forEach((k) => {
    max[k] = QUESTIONS.reduce(
      (sum, q) => sum + Math.max(...q.a.map((o) => o.s[k] || 0)),
      0
    );
  });
  return max;
})();

export function scoreToRanked(raw) {
  return Object.keys(TYPES)
    .map((k) => {
      const ratio = (raw[k] || 0) / MAX_BY_TYPE[k];
      return { ...TYPES[k], raw: raw[k] || 0, ratio, pct: Math.round(ratio * 100) };
    })
    .sort((a, b) => b.ratio - a.ratio);
}
