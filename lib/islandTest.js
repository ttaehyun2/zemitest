/** 점수(0~100)를 생존 일수로 환산합니다. */
export function toDays(score) {
  if (score >= 95) return 365;
  if (score <= 5) return 1;
  // 지수적으로 늘어나게 (낮은 점수 구간은 촘촘하게)
  return Math.max(1, Math.round(Math.pow(score / 100, 2.6) * 360 + score / 10));
}

